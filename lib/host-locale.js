let activeLanguage = "zh";
export function setHostLanguage(language) {
  activeLanguage = language === "ru" ? "ru" : language === "zh" ? "zh" : "en";
}
export function getHostLanguage() { return activeLanguage; }
export function hostMessage(key, vars) {
  const dict = dictionaries[activeLanguage] || dictionaries.zh;
  const text = dict[key] ?? key;
  if (!vars || typeof text !== "string") return text;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] !== undefined ? vars[name] : "{" + name + "}");
}
